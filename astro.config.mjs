// @ts-check
import { env } from "node:process";
import { writeFile } from "node:fs/promises";
import { defineConfig } from "astro/config";

const target = env.SITE_TARGET ?? "international";

if (!["international", "serbian"].includes(target)) {
  throw new Error(`Unknown SITE_TARGET: ${target}`);
}

export default defineConfig({
  site:
    target === "serbian"
      ? "https://pismaizsarajeva.com"
      : "https://lettersfromsarajevo.com",
  output: "static",
  outDir: `./dist/${target}`,
  trailingSlash: "always",
  integrations: [
    {
      name: "netlify-static-routing",
      hooks: {
        "astro:build:done": async ({ dir, pages }) => {
          const rules = [
            "# Generated by astro.config.mjs; do not edit the build output.",
          ];
          const homes =
            target === "serbian"
              ? {
                  sr: "/",
                  en: "https://lettersfromsarajevo.com/",
                  ru: "https://lettersfromsarajevo.com/ru/",
                  "pt-br": "https://lettersfromsarajevo.com/pt-br/",
                  el: "https://lettersfromsarajevo.com/el/",
                  hu: "https://lettersfromsarajevo.com/hu/",
                }
              : { en: "/", sr: "https://pismaizsarajeva.com/" };

          // Force these over the static HTML redirect pages emitted by Astro.
          for (const [lang, destination] of Object.entries(homes)) {
            rules.push(
              `/${lang} ${destination} 301!`,
              `/${lang}/ ${destination} 301!`,
            );
            rules.push(`/${lang}/index.html ${destination} 301!`);
          }

          // Keep Jekyll's .html URLs for the original languages' reading and About pages.
          for (const { pathname } of pages) {
            const path = `/${pathname.replace(/^\/+|\/+$/g, "")}`;
            if (
              /^\/(en|sr|ru|pt-br)\/[^/]+$/.test(path) &&
              !path.endsWith("/404")
            ) {
              rules.push(`${path}.html ${path}/ 301!`);
            }
          }

          rules.push("/public/img/* /img/:splat 301");
          // Unforced rules allow real files to win and preserve the HTTP 404 status.
          for (const lang of ["en", "sr", "ru", "pt-br", "el", "hu"]) {
            rules.push(`/${lang}/* /${lang}/404/index.html 404`);
          }
          rules.push("/* /404.html 404");
          await writeFile(new URL("_redirects", dir), `${rules.join("\n")}\n`);
        },
      },
    },
  ],
});
